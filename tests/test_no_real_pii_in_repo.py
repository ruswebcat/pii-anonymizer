# START_BLOCK_SCAN_TREE
def scan_tree(
    root: Path,
    files: list[Path] | None = None,
    extra_digests: frozenset[str] = frozenset(),
    extra_proper_noun: frozenset[str] = frozenset(),
) -> list[tuple[str, int, str, str]]:
    """Return forbidden findings under ``root`` as (file, line, masked value, kind).

    # START_CONTRACT: scan_tree
    #   PURPOSE: Найти все телефоноподобные, почтоподобные, запрещённые и чужие адресные значения.
    #   INPUTS: { root: Path - каталог сканирования, files: list[Path] | None - явный список файлов, extra_digests: frozenset[str] - отпечатки отличительных значений контроля, extra_proper_noun: frozenset[str] - отпечатки общеупотребительных значений контроля }
    #   OUTPUTS: { list[tuple[str, int, str, str]] - файл, строка, замаскированное значение, вид находки }
    #   SIDE_EFFECTS: читает файлы дерева
    #   LINKS: V-M-REPO-HYGIENE
    # END_CONTRACT: scan_tree
    """
    findings: list[tuple[str, int, str, str]] = []
    targets = files if files is not None else iter_targets(root)
    for path in targets:
        try:
            lines = path.read_text(encoding="utf-8", errors="replace").splitlines()
        except OSError:
            continue
        relative = path.relative_to(root) if root in path.parents or root == path.parent else path
        for number, line in enumerate(lines, 1):
            for match in PHONE_RE.finditer(line):
                value = match.group(0)
                if not looks_like_stub_phone(value):
                    findings.append((str(relative), number, mask(value), "phone"))
            for match in EMAIL_RE.finditer(line):
                value = match.group(0)
                if not looks_like_stub_email(value):
                    findings.append((str(relative), number, mask(value), "email"))
            for value in secrets_in(line):
                findings.append((str(relative), number, mask(value), "secret"))
            for value in foreign_ipv4(line):
                findings.append((str(relative), number, mask(value), "foreign_ip"))
            for match in TOKEN_RE.finditer(line):
                value = match.group(0).strip(".,;:()[]{}<>" + chr(34) + chr(39) + chr(96))
                if not value:
                    continue
                reason = is_forbidden(value, extra_digests, extra_proper_noun, line[: match.start()])
                if reason is not None:
                    findings.append((str(relative), number, f"{mask(value)} — {reason}", "forbidden"))
    return findings


def iter_targets(root: Path) -> list[Path]:
    """Return the files the rule covers: the repository layout or every file of a small tree."""
    targets: list[Path] = []
    for name in SCAN_ROOT_FILES:
        candidate = root / name
        if candidate.is_file():
            targets.append(candidate)
    for directory in SCAN_DIRS:
        base = root / directory
        if not base.is_dir():
            continue
        for path in sorted(base.rglob("*")):
            if not path.is_file() or path.suffix.lower() not in SCAN_SUFFIXES:
                continue
            if SKIP_DIR_NAMES.intersection(path.parts):
                continue
            if any(str(path.relative_to(root)).startswith(prefix) for prefix in THIRD_PARTY_DIRS):
                continue
            targets.append(path)
    if targets:
        return targets
    # Небольшое дерево (например временное): берём всё, что подходит по расширению.
    return sorted(
        path
        for path in root.rglob("*")
        if path.is_file()
        and path.suffix.lower() in SCAN_SUFFIXES
        and not SKIP_DIR_NAMES.intersection(path.parts)
    )
# END_BLOCK_SCAN_TREE


