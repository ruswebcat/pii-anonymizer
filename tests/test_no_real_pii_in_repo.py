def secrets_in(line: str) -> list[str]:
    """Return values in a line that look like a real key, token or password.

    # START_CONTRACT: secrets_in
    #   PURPOSE: Не дать настоящему ключу попасть в дерево публичной сборки.
    #   INPUTS: { line: str - строка файла }
    #   OUTPUTS: { list[str] - найденные значения }
    #   SIDE_EFFECTS: none
    #   LINKS: V-M-REPO-HYGIENE
    # END_CONTRACT: secrets_in
    """
    found = SECRET_PREFIX_RE.findall(line)
    for value in SECRET_ASSIGNED_RE.findall(line):
        if any(character.isdigit() for character in value):
            found.append(value)
    return found
